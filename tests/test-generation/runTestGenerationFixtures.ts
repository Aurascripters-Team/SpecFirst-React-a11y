  assert.equal(result.nextPhase.demoRoute, "/specfirst/generated/SelectOnlyCombobox");
  assert.match(result.testFileHash, /^sha256:[a-f0-9]{64}$/);
  assert.match(result.harnessFileHash, /^sha256:[a-f0-9]{64}$/);
