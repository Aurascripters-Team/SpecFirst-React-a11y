function testSkippedAndFailedLockedSpecs(): void {
  const skippedProject = createEmptyProject("skipped");
  const skippedSpec = {
    schemaVersion: "1.0.0",
    status: "skipped",
    component: { name: "SelectOnlyCombobox", path: "tests/fixtures/NamedFunctionCombobox.tsx" },
    reason: "manifest_load_skipped",
    message: "Skipped fixture.",
    upstream: { manifestCanContinue: false },
    nextPhase: { canContinue: false },
  };
  writeJson(path.join(skippedProject.runDir, "lockedSpec.json"), skippedSpec);
  const skipped = generateTests({
    input: path.join(skippedProject.runDir, "lockedSpec.json"),
    projectRoot: skippedProject.root,
  });
  assert.equal(skipped.status, "skipped");
  assert.equal(fs.existsSync(path.join(skippedProject.root, "tests", "a11y", "SelectOnlyCombobox.spec.ts")), false);

  const failedProject = createEmptyProject("failed");
  const failedSpec = {
    schemaVersion: "1.0.0",
    status: "failed",
    reason: "missing_checks",
    message: "Failed fixture.",
    nextPhase: { canContinue: false },
  };
  writeJson(path.join(failedProject.runDir, "lockedSpec.json"), failedSpec);
  const failed = generateTests({
    input: path.join(failedProject.runDir, "lockedSpec.json"),
    projectRoot: failedProject.root,
  });
  assertFailed(failed, "locked_spec_not_locked");
  assert.equal(fs.existsSync(path.join(failedProject.root, "tests", "a11y", "SelectOnlyCombobox.spec.ts")), false);
}

function assertFailed(result: TestGenerationResult, reason: string): void {
  assert.equal(result.status, "failed");
  if (result.status === "failed") {
    assert.equal(result.reason, reason);
    assert.equal(result.nextPhase.canContinue, false);
  }
}

function createProject(name: string): { root: string; runDir: string } {
  const project = createEmptyProject(name);
  fs.mkdirSync(path.join(project.root, "tests", "fixtures"), { recursive: true });
  fs.copyFileSync(fixtureComponentPath, path.join(project.root, "tests", "fixtures", "NamedFunctionCombobox.tsx"));
  fs.copyFileSync(fixtureLockedSpecPath, path.join(project.runDir, "lockedSpec.json"));
  return project;
}

function createEmptyProject(name: string): { root: string; runDir: string } {
  const root = path.join(tmpRoot, name);
  const runDir = path.join(root, "specfirst", "runs", "test-run");
  fs.mkdirSync(runDir, { recursive: true });
  return { root, runDir };
}

function rewriteLockedSpecHash(lockedSpec: LockedSpecSuccess): void {
  const hashInput = {
    ...lockedSpec,
    integrity: {
      ...lockedSpec.integrity,
      hash: null,
    },
  };
  lockedSpec.integrity.hash = hashCanonical(hashInput);
}

function hashCanonical(value: unknown): string {
  return `sha256:${crypto.createHash("sha256").update(JSON.stringify(canonicalize(value))).digest("hex")}`;
}

function canonicalize(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(canonicalize);
  }

  if (value && typeof value === "object") {
    const record = value as Record<string, unknown>;
    return Object.fromEntries(Object.keys(record).sort().map((key) => [key, canonicalize(record[key])]));
  }

  return value;
}

function readText(filePath: string): string {
  return fs.readFileSync(filePath, "utf8");
}

function readJson<T>(filePath: string): T {
  return JSON.parse(readText(filePath)) as T;
}

function writeJson(filePath: string, value: unknown): void {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`);
}
