function testDeterministicGeneration(first: TestGenerationGenerated): void {
  const project = createProject("deterministic");
  const firstRun = generateTests({
    input: path.join(project.runDir, "lockedSpec.json"),
    projectRoot: project.root,
  });
  const secondRun = generateTests({
    input: path.join(project.runDir, "lockedSpec.json"),
    projectRoot: project.root,
  });

  assert.equal(firstRun.status, "generated");
  assert.equal(secondRun.status, "generated");
  if (firstRun.status === "generated" && secondRun.status === "generated") {
    assert.equal(secondRun.testFileHash, firstRun.testFileHash);
    assert.equal(secondRun.harnessFileHash, firstRun.harnessFileHash);
    assert.equal(secondRun.generatedArtifactHashes.combined, firstRun.generatedArtifactHashes.combined);
    assert.equal(first.testCount, secondRun.testCount);
  }
}

function testTamperedHashFailure(): void {
  const project = createProject("tampered-hash");
  const lockedSpecPath = path.join(project.runDir, "lockedSpec.json");
  const lockedSpec = readJson<LockedSpecSuccess>(lockedSpecPath);
  lockedSpec.checks[0].description = "Tampered after lock.";
  writeJson(lockedSpecPath, lockedSpec);

  const result = generateTests({
    input: lockedSpecPath,
    projectRoot: project.root,
  });

  assertFailed(result, "locked_spec_hash_mismatch");
}

function testUnsupportedStrategyFailure(): void {
  const project = createProject("unsupported-strategy");
  const lockedSpecPath = path.join(project.runDir, "lockedSpec.json");
  const lockedSpec = readJson<LockedSpecSuccess>(lockedSpecPath);
  lockedSpec.checks[0].testStrategy = "model-written-test";
  rewriteLockedSpecHash(lockedSpec);
  writeJson(lockedSpecPath, lockedSpec);

  const result = generateTests({
    input: lockedSpecPath,
    projectRoot: project.root,
  });

  assertFailed(result, "unsupported_test_strategy");
}

