  const testFile = readText(path.join(project.root, result.testFilePath));
  assert.ok(testFile.includes("AUTO-GENERATED BY SPECFIRST"));
  assert.ok(testFile.includes("Bob must not edit this file."));
  assert.ok(testFile.includes("Source locked spec: specfirst/runs/test-run/lockedSpec.json"));
